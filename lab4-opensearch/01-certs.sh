#!/usr/bin/env bash
# Lab 4 · Step 1 · OpenSearch certificates and their secrets in the DX namespace.
#
# OpenSearch and the Search Middleware talk over mutual TLS. HCL asks for three certificates
# signed by the same CA:
#   admin   -> OpenSearch administration (its DN goes in configuration.openSearch.security.adminDN)
#   node    -> CN=opensearch-node    (node-to-node communication; the CN is preconfigured)
#   client  -> CN=opensearch-client  (the Search Middleware as a client; CN preconfigured)
# with the X.509 extensions basicConstraints=CA:FALSE, keyUsage=digitalSignature,keyEncipherment
# and extendedKeyUsage=serverAuth,clientAuth. Keys in unencrypted PKCS#8.
#
# Here a lab CA is created. With the company PKI, sign them with its CA and create the same
# three secrets (see GUIDE, "Corporate CA").
#
# It also generates admin-dn.rendered.yaml with the adminDN in RFC 2253 format (used by 02-search-install.sh).
set -euo pipefail
source "$(dirname "$0")/../common/lib.sh"
require_cmd openssl
require_vars DX_NS
cd "$(dirname "$0")"

D=certs; mkdir -p "$D"; umask 077
SUBJ="/C=ES/O=EUROPESIP/OU=DX Compose Labs"
EXT="$D/ext.cnf"
cat > "$EXT" <<'CNF'
basicConstraints = CA:FALSE
keyUsage = digitalSignature, keyEncipherment
extendedKeyUsage = serverAuth, clientAuth
CNF

if [[ ! -f "$D/root-ca.pem" ]]; then
  info "Lab CA"
  openssl genrsa -out "$D/root-ca-key.pem" 2048 2>/dev/null
  openssl req -new -x509 -sha256 -key "$D/root-ca-key.pem" -subj "$SUBJ/CN=dx-search-root-ca" -out "$D/root-ca.pem" -days 730
fi

cert() {  # cert <name> <CN>
  [[ -f "$D/$1.pem" ]] && { ok "$1.pem already exists"; return; }
  openssl genrsa -out "$D/$1-key-temp.pem" 2048 2>/dev/null
  openssl pkcs8 -inform PEM -outform PEM -in "$D/$1-key-temp.pem" -topk8 -nocrypt -out "$D/$1-key.pem"
  openssl req -new -key "$D/$1-key.pem" -subj "$SUBJ/CN=$2" -out "$D/$1.csr"
  openssl x509 -req -in "$D/$1.csr" -CA "$D/root-ca.pem" -CAkey "$D/root-ca-key.pem" -CAcreateserial \
    -sha256 -days 730 -extfile "$EXT" -out "$D/$1.pem" 2>/dev/null
  rm -f "$D/$1-key-temp.pem" "$D/$1.csr"
  ok "$1.pem  ($(openssl x509 -in "$D/$1.pem" -noout -subject -nameopt RFC2253 | sed 's/^subject=//'))"
}
info "Certificates signed by the CA"
cert admin  admin
cert node   opensearch-node
cert client opensearch-client

info "Secrets in $DX_NS (default names of the hcl-dx-search chart)"
apply_secret "$DX_NS" generic search-admin-cert  --from-file="$D/admin.pem"  --from-file="$D/admin-key.pem"  --from-file="$D/root-ca.pem"
apply_secret "$DX_NS" generic search-node-cert   --from-file="$D/node.pem"   --from-file="$D/node-key.pem"   --from-file="$D/root-ca.pem"
apply_secret "$DX_NS" generic search-client-cert --from-file="$D/client.pem" --from-file="$D/client-key.pem" --from-file="$D/root-ca.pem"

# adminDN as OpenSearch compares it: RFC 2253 (reverse order: CN first) and in single quotes
# in YAML. HCL advises against passing it with --set: it goes in a values file.
DN=$(openssl x509 -in "$D/admin.pem" -noout -subject -nameopt RFC2253 | sed 's/^subject=//')
cat > admin-dn.rendered.yaml <<YAML
# Generated by 01-certs.sh: DN of the admin certificate in RFC 2253 format
configuration:
  openSearch:
    security:
      adminDN: '${DN//\'/\'\'}'
YAML
info "adminDN = $DN   (admin-dn.rendered.yaml)"
