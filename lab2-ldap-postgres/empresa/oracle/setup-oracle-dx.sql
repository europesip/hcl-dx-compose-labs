-- Lab 2 · Rama empresarial · Preparación de Oracle para el Web Engine de DX Compose
--
-- Basado en el script de ejemplo de HCL (SetupOracleDatabasesManually.sql, DX Compose CF238).
-- Crea, dentro de la PDB:
--   - el usuario con el que se conecta DX (DX_DB_USER, p. ej. wpsuser)
--   - un usuario/esquema por dominio: release, community, customization, jcr, feedback, likeminds
--   - los roles WP_BASE_*, WP_JCR_*, WP_PZN_* (CONFIG y RUNTIME) que referencian las properties
--   - los tablespaces del JCR: ICMLFQ32, ICMLNF32, ICMVFQ04, ICMSFQ04, ICMLSNDX
--
-- Requisitos de HCL: Oracle 19c o 21c, juego de caracteres AL32UTF8 / AL16UTF16.
-- Ejecución (como SYSDBA o un DBA de la PDB); SQL*Plus pide las variables:
--   sqlplus / as sysdba @setup-oracle-dx.sql
-- Revísalo con tu DBA: privilegios (GRANT DBA, ANY TABLE...) y tablespaces según vuestra política.
-- ------------------------------------------------------------------------------------------
SET VERIFY OFF
ACCEPT PDB_NAME       CHAR DEFAULT 'WPSDB'   PROMPT 'PDB de DX [WPSDB]: '
ACCEPT DX_DB_USER     CHAR DEFAULT 'wpsuser' PROMPT 'Usuario de conexion de DX [wpsuser]: '
ACCEPT DX_DB_PASSWORD CHAR HIDE              PROMPT 'Contrasena para todos los usuarios de DX: '

ALTER SESSION SET CONTAINER = &&PDB_NAME;

CREATE USER &&DX_DB_USER
	IDENTIFIED BY "&&DX_DB_PASSWORD"
	DEFAULT TABLESPACE USERS
	TEMPORARY TABLESPACE TEMP;

--------------------------------------------------------------
-- SETUP for schema RELEASE
--------------------------------------------------------------
CREATE USER release
	IDENTIFIED BY "&&DX_DB_PASSWORD"
	DEFAULT TABLESPACE USERS
	TEMPORARY TABLESPACE TEMP;


GRANT UNLIMITED TABLESPACE TO release;

CREATE ROLE WP_BASE_CONFIG_USERS NOT IDENTIFIED;
GRANT ALTER ANY TABLE, CREATE ANY TABLE, DROP ANY TABLE,
	CREATE ANY INDEX, DROP ANY INDEX,
	INSERT ANY TABLE, UPDATE ANY TABLE, SELECT ANY TABLE, DELETE ANY TABLE,
	CREATE SESSION
	TO WP_BASE_CONFIG_USERS;


GRANT SELECT ON DBA_PENDING_TRANSACTIONS TO WP_BASE_CONFIG_USERS;
GRANT WP_BASE_CONFIG_USERS TO &&DX_DB_USER;


CREATE ROLE WP_BASE_RUNTIME_USERS NOT IDENTIFIED;
GRANT CREATE SESSION TO WP_BASE_RUNTIME_USERS;
GRANT SELECT ON DBA_PENDING_TRANSACTIONS TO WP_BASE_RUNTIME_USERS;
GRANT WP_BASE_RUNTIME_USERS TO &&DX_DB_USER;

--------------------------------------------------------------
-- SETUP for schema COMMUNITY
--------------------------------------------------------------
