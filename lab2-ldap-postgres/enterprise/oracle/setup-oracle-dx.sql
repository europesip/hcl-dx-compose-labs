-- ------------------------------------------------------------------------------------------
-- Lab 2 · Enterprise branch · Oracle preparation for the DX Compose Web Engine
--
-- Based on the HCL sample script (SetupOracleDatabasesManually.sql, DX Compose CF238).
-- Creates, inside the PDB:
--   - the user DX connects with (DX_DB_USER, e.g. wpsuser)
--   - one user/schema per domain: release, community, customization, jcr, feedback, likeminds
--   - the WP_BASE_*, WP_JCR_*, WP_PZN_* roles (CONFIG and RUNTIME) referenced by the properties
--   - the JCR tablespaces: ICMLFQ32, ICMLNF32, ICMVFQ04, ICMSFQ04, ICMLSNDX
--
-- HCL requirements: Oracle 19c or 21c, AL32UTF8 / AL16UTF16 character set.
-- Run it (as SYSDBA or a PDB DBA); SQL*Plus prompts for the variables:
--   sqlplus / as sysdba @setup-oracle-dx.sql
-- Review it with your DBA: privileges (GRANT DBA, ANY TABLE...) and tablespaces per your policy.
-- ------------------------------------------------------------------------------------------
SET VERIFY OFF
ACCEPT PDB_NAME       CHAR DEFAULT 'WPSDB'   PROMPT 'DX PDB [WPSDB]: '
ACCEPT DX_DB_USER     CHAR DEFAULT 'wpsuser' PROMPT 'DX connection user [wpsuser]: '
ACCEPT DX_DB_PASSWORD CHAR HIDE              PROMPT 'Password for every DX user: '

ALTER SESSION SET CONTAINER = &&PDB_NAME;

CREATE USER &&DX_DB_USER
	IDENTIFIED BY "&&DX_DB_PASSWORD"
	DEFAULT TABLESPACE USERS
	TEMPORARY TABLESPACE TEMP;

--------------------------------------------------------------
-- SETUP for schema RELEASE
--------------------------------------------------------------
CREATE USER release
	IDENTIFIED BY "&&DX_DB_PASSWORD"
	DEFAULT TABLESPACE USERS
	TEMPORARY TABLESPACE TEMP;


GRANT UNLIMITED TABLESPACE TO release;

CREATE ROLE WP_BASE_CONFIG_USERS NOT IDENTIFIED;
GRANT ALTER ANY TABLE, CREATE ANY TABLE, DROP ANY TABLE,
	CREATE ANY INDEX, DROP ANY INDEX,
	INSERT ANY TABLE, UPDATE ANY TABLE, SELECT ANY TABLE, DELETE ANY TABLE,
	CREATE SESSION
	TO WP_BASE_CONFIG_USERS;


GRANT SELECT ON DBA_PENDING_TRANSACTIONS TO WP_BASE_CONFIG_USERS;
GRANT WP_BASE_CONFIG_USERS TO &&DX_DB_USER;


CREATE ROLE WP_BASE_RUNTIME_USERS NOT IDENTIFIED;
GRANT CREATE SESSION TO WP_BASE_RUNTIME_USERS;
GRANT SELECT ON DBA_PENDING_TRANSACTIONS TO WP_BASE_RUNTIME_USERS;
GRANT WP_BASE_RUNTIME_USERS TO &&DX_DB_USER;

--------------------------------------------------------------
-- SETUP for schema COMMUNITY
--------------------------------------------------------------
