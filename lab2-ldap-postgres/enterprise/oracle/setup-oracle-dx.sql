	CREATE ANY INDEX, DROP ANY INDEX,
	INSERT ANY TABLE, UPDATE ANY TABLE, SELECT ANY TABLE, DELETE ANY TABLE,
	CREATE SESSION
	TO WP_BASE_CONFIG_USERS;


GRANT SELECT ON DBA_PENDING_TRANSACTIONS TO WP_BASE_CONFIG_USERS;
