--------------------------------------------------------------
-- TABLESPACE CREATION
--------------------------------------------------------------
-- Create a TABLESPACE
-- Might need to Update the database directory path for your Oracle version.
CREATE TABLESPACE ICMLFQ32
    DATAFILE SIZE 300M
    AUTOEXTEND ON NEXT 10M MAXSIZE UNLIMITED
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE;

CREATE TABLESPACE ICMLNF32
    DATAFILE SIZE 25M
    AUTOEXTEND ON NEXT 10M MAXSIZE UNLIMITED
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE;

CREATE TABLESPACE ICMVFQ04
    DATAFILE SIZE 25M
    AUTOEXTEND ON NEXT 10M MAXSIZE UNLIMITED
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE;

CREATE TABLESPACE ICMSFQ04
    DATAFILE SIZE 150M
    AUTOEXTEND ON NEXT 10M MAXSIZE UNLIMITED
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE;

CREATE TABLESPACE ICMLSNDX
    DATAFILE SIZE 10M
    AUTOEXTEND ON NEXT 10M MAXSIZE UNLIMITED
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE;

--------------------------------------------------------------
-- For timer tables
--------------------------------------------------------------
GRANT DBA TO &&DX_DB_USER;
GRANT SELECT ANY SEQUENCE, DROP ANY SEQUENCE TO WP_BASE_CONFIG_USERS;
GRANT SELECT ANY SEQUENCE, DROP ANY SEQUENCE TO WP_BASE_RUNTIME_USERS;
