#!/usr/bin/env python3
"""Copy the lab files used by the wizard's direct installation (option C) into docs/index.html.

Option C produces a self-contained bundle: the wizard renders these files with the user's values,
so it has to carry a copy of them. This script keeps that copy identical to the repository files.

Usage:  tools/sync-wizard-templates.py           rewrite the TPL block of docs/index.html
        tools/sync-wizard-templates.py --check   exit 1 if the copy is out of date (no changes)
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "index.html"
BEGIN = "// BEGIN LAB TEMPLATES"
END = "// END LAB TEMPLATES"

# setup-postgres-dx.sql is deliberately NOT here: it is not published.
FILES = [
    "common/openshift/namespaces.yaml",
    "common/collect-support-data.sh",
    "lab0-poc-wsl/storage-poc.yaml",
    "lab0-poc-wsl/dam-binaries-pv.yaml",
    "lab0-poc-wsl/custom-values.poc.yaml",
    "lab0-poc-wsl/custom-search-values.poc.yaml",
    "lab0-poc-wsl/traefik-config.yaml",
    "lab1-dx-base/custom-values.yaml",
    "lab1-dx-base/ingress-dx.yaml",
    "lab1-dx-base/ingressroute-dx-traefik.yaml",
    "lab1-dx-base/route-dx-openshift.yaml",
    "lab2-ldap-postgres/a-ldap/openldap-values.yaml",
    "lab2-ldap-postgres/a-ldap/demo-users.ldif",
    "lab2-ldap-postgres/a-ldap/custom-values.ldap.yaml",
    "lab2-ldap-postgres/enterprise/active-directory/custom-values.ad.yaml",
    "lab2-ldap-postgres/b-postgres/cluster-dx-pg.yaml",
    "lab2-ldap-postgres/b-postgres/custom-values.postgres.yaml",
    "lab2-ldap-postgres/b-postgres/dx_dbtype.properties",
    "lab2-ldap-postgres/b-postgres/dx_dbdomain.properties.template",
    "lab2-ldap-postgres/enterprise/oracle/custom-values.oracle.yaml",
    "lab2-ldap-postgres/enterprise/oracle/dx_dbtype.properties",
    "lab2-ldap-postgres/enterprise/oracle/dx_dbdomain.properties.template",
    "lab3-iq-openrouter/litellm-values.yaml",
    "lab3-iq-openrouter/custom-iq-values.yaml",
    "lab3-iq-openrouter/custom-iq-values.db-external.yaml",
    "lab3-iq-openrouter/custom-values.iq.yaml",
    "lab3-iq-openrouter/iq-chat.py",
    "lab3-iq-openrouter/custom-mcp/server.py",
    "lab3-iq-openrouter/custom-mcp/europesip-mcp.yaml",
    "lab4-opensearch/custom-search-values.yaml",
    "lab4-opensearch/custom-values.search.yaml",
]


def block() -> str:
    lines = [BEGIN + " (generated by tools/sync-wizard-templates.py: do not edit by hand)", "const TPL = {"]
    for f in FILES:
        text = (ROOT / f).read_text(encoding="utf-8")
        # "</" would end the inline <script>: escape it inside the JS strings
        value = json.dumps(text, ensure_ascii=False).replace("</", "<\\/")
        lines.append(f"  {json.dumps(f)}: {value},")
    lines += ["};", END]
    return "\n".join(lines)


def main() -> int:
    page = PAGE.read_text(encoding="utf-8")
    i, j = page.index(BEGIN), page.index(END) + len(END)
    new = page[:i] + block() + page[j:]
    if "--check" in sys.argv:
        if new != page:
            print("docs/index.html is out of date: run tools/sync-wizard-templates.py")
            return 1
        print("docs/index.html templates are up to date")
        return 0
    PAGE.write_text(new, encoding="utf-8")
    print(f"docs/index.html: {len(FILES)} templates synchronised")
    return 0


if __name__ == "__main__":
    sys.exit(main())
